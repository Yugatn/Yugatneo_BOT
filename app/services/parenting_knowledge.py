def find_topics(query: str) -> tuple[ParentingTopic, ...]:
    needle = query.strip().casefold()
    if not needle:
        return TOPICS
    return tuple(
        topic for topic in TOPICS
        if needle in topic.key.casefold()
        or needle in topic.title.casefold()
        or any(needle in tag.casefold() for tag in topic.tags)
    )


def format_topic(topic: ParentingTopic) -> str:
    return (
        f"📘 {topic.title} (возрастной ориентир: {topic.ages})\n\n"
        f"{topic.summary}\n\n"
        f"💬 Вопрос для размышления: {topic.coaching_question}\n\n"
        f"Уровень обоснования: {topic.evidence}\n"
        f"Ориентиры для проверки: {', '.join(topic.references)}.\n\n"
        "Это образовательная информация, не диагностика и не индивидуальная терапия."
    )
